// Sơ đồ ghế khớp chuẩn Figma Screen 3
export function generateMockSeats(roomId: number = 1): Seat[] {
  const rows = ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'];
  const seats: Seat[] = [];
  let seatId = 1;

  rows.forEach((row, rowIdx) => {
    const isCouple = row === 'H';
    const isVip = row === 'E' || row === 'F' || row === 'G';
    const typeId = isCouple ? 3 : isVip ? 2 : 1;
    const typeCode = isCouple ? 'COUPLE' : isVip ? 'VIP' : 'STANDARD';

    if (isCouple) {
      // 5 ghế đôi ở hàng H
      for (let c = 1; c <= 5; c++) {
        seats.push({
          id: seatId++,
          room_id: roomId,
          seat_type_id: typeId,
          row_label: row,
          seat_number: c,
          grid_row: rowIdx + 1,
          grid_col: c,
          is_active: true,
          seat_type: {
            id: typeId,
            code: typeCode,
            name: 'Ghế đôi',
            capacity: 2,
            color_code: '#F472B6',
          },
          status: 'AVAILABLE',
        });
      }
    } else {
      // 10 ghế mỗi hàng (5 ghế bên trái, 5 ghế bên phải)
      for (let c = 1; c <= 10; c++) {
        seats.push({
          id: seatId++,
          room_id: roomId,
          seat_type_id: typeId,
          row_label: row,
          seat_number: c,
          grid_row: rowIdx + 1,
          grid_col: c,
          is_active: true,
          seat_type: {
            id: typeId,
            code: typeCode,
            name: isVip ? 'Ghế VIP' : 'Ghế thường',
            capacity: 1,
            color_code: isVip ? '#FABF2E' : '#9CA3AF',
          },
          status: 'AVAILABLE',
        });
      }
    }
  });

  return seats;
}
